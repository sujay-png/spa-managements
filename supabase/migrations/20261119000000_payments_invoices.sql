-- 1. Business ref of the logged-in user (reads "Useraccount")
create or replace function public.spa_current_business_ref()
returns bigint language plpgsql stable security definer set search_path = public as $$
declare v_tbl text; v_col text; v_ref text;
begin
  select table_name into v_tbl from information_schema.tables
  where table_schema = 'public'
    and lower(table_name) in ('useraccount', 'useraccounts', 'user_account')
  order by case when table_name = 'Useraccount' then 0 else 1 end
  limit 1;
  if v_tbl is null then return null; end if;

  select column_name into v_col from information_schema.columns
  where table_schema = 'public' and table_name = v_tbl
    and lower(replace(column_name, '_', '')) in
        ('userbusinessref', 'businessref', 'userbusinessid', 'businessid')
  order by case lower(replace(column_name, '_', ''))
             when 'userbusinessref' then 1 when 'businessref' then 2 else 3 end
  limit 1;
  if v_col is null then return null; end if;

  execute format('select %I::text from public.%I where id::text = $1 limit 1', v_col, v_tbl)
    into v_ref using auth.uid()::text;
  return nullif(trim(v_ref), '')::bigint;
end $$;
grant execute on function public.spa_current_business_ref() to authenticated;

-- 2. Billing settings
create table if not exists public.spa_billing_settings (
  business_ref     bigint primary key,
  business_name    text,
  address          text,
  phone            text,
  email            text,
  gstin            text,
  upi_id           text,
  upi_payee_name   text,
  invoice_prefix   text not null default 'INV',
  default_gst_rate numeric(5,2) not null default 18,
  gst_inclusive    boolean not null default false,
  sac_code         text not null default '999722',
  footer_note      text default 'Thank you for visiting. We look forward to seeing you again!',
  updated_at       timestamptz not null default now()
);
alter table public.spa_billing_settings enable row level security;
drop policy if exists "spa_billing_settings business access" on public.spa_billing_settings;
create policy "spa_billing_settings business access" on public.spa_billing_settings
  for all to authenticated
  using (business_ref = public.spa_current_business_ref())
  with check (business_ref = public.spa_current_business_ref());

-- 3. Invoices
create table if not exists public.spa_invoices (
  id              bigint generated by default as identity primary key,
  business_ref    bigint not null,
  booking_id      bigint,
  invoice_number  text not null,
  customer_name   text not null default '',
  customer_phone  text,
  therapist       text,
  service_date    timestamptz,
  items           jsonb not null default '[]'::jsonb,
  subtotal        numeric(12,2) not null default 0,
  discount        numeric(12,2) not null default 0,
  taxable_amount  numeric(12,2) not null default 0,
  gst_rate        numeric(5,2)  not null default 0,
  cgst            numeric(12,2) not null default 0,
  sgst            numeric(12,2) not null default 0,
  round_off       numeric(6,2)  not null default 0,
  total           numeric(12,2) not null default 0,
  payment_status  text not null default 'unpaid'
                  check (payment_status in ('unpaid', 'paid', 'void')),
  payment_method  text,
  payment_ref     text,
  paid_at         timestamptz,
  notes           text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (business_ref, invoice_number)
);
create index if not exists spa_invoices_business_created_idx on public.spa_invoices (business_ref, created_at desc);
create index if not exists spa_invoices_booking_idx          on public.spa_invoices (booking_id);
create index if not exists spa_invoices_business_paid_idx    on public.spa_invoices (business_ref, paid_at desc);

alter table public.spa_invoices enable row level security;
drop policy if exists "spa_invoices business access" on public.spa_invoices;
create policy "spa_invoices business access" on public.spa_invoices
  for all to authenticated
  using (business_ref = public.spa_current_business_ref())
  with check (business_ref = public.spa_current_business_ref());

create or replace function public.spa_touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists spa_invoices_touch on public.spa_invoices;
create trigger spa_invoices_touch before update on public.spa_invoices
  for each row execute function public.spa_touch_updated_at();

drop trigger if exists spa_billing_settings_touch on public.spa_billing_settings;
create trigger spa_billing_settings_touch before update on public.spa_billing_settings
  for each row execute function public.spa_touch_updated_at();

-- 4. Sequential invoice numbers per financial year:  PREFIX/26-27/0001
create table if not exists public.spa_invoice_counters (
  business_ref bigint not null,
  fiscal_year  text   not null,
  last_number  integer not null default 0,
  primary key (business_ref, fiscal_year)
);
alter table public.spa_invoice_counters enable row level security;

create or replace function public.spa_next_invoice_number(p_business_ref bigint, p_prefix text default 'INV')
returns text language plpgsql security definer set search_path = public as $$
declare
  v_now   date := (now() at time zone 'Asia/Kolkata')::date;
  v_start int  := case when extract(month from v_now) >= 4
                       then extract(year from v_now)::int
                       else extract(year from v_now)::int - 1 end;
  v_fy    text := lpad((v_start % 100)::text, 2, '0') || '-' || lpad(((v_start + 1) % 100)::text, 2, '0');
  v_no    int;
begin
  if p_business_ref is distinct from public.spa_current_business_ref() then
    raise exception 'not allowed for this business';
  end if;
  insert into public.spa_invoice_counters (business_ref, fiscal_year, last_number)
  values (p_business_ref, v_fy, 1)
  on conflict (business_ref, fiscal_year)
  do update set last_number = public.spa_invoice_counters.last_number + 1
  returning last_number into v_no;
  return coalesce(nullif(trim(p_prefix), ''), 'INV') || '/' || v_fy || '/' || lpad(v_no::text, 4, '0');
end $$;
grant execute on function public.spa_next_invoice_number(bigint, text) to authenticated;

-- 5. Link Booking → invoice (optional)
do $$
declare v_tbl text;
begin
  select table_name into v_tbl from information_schema.tables
  where table_schema = 'public' and table_type = 'BASE TABLE'
    and lower(table_name) in ('booking', 'bookings')
  order by case when table_name = 'Booking' then 0 else 1 end
  limit 1;
  if v_tbl is not null then
    execute format('alter table public.%I add column if not exists invoice_id bigint', v_tbl);
  end if;
end $$;

